#!/usr/bin/env python3
"""Regenerate after updating @fontsource/iosevka: nix develop -c python3 scripts/subset-iosevka.py."""
from pathlib import Path
import subprocess
import tempfile

from fontTools.ttLib import TTFont

root = Path(__file__).resolve().parent.parent
source = root / 'node_modules/@fontsource/iosevka/files/iosevka-latin-400-normal.woff2'
out = root / 'src/assets/fonts'
out.mkdir(parents=True, exist_ok=True)
original = TTFont(source)
characters = set(original.getBestCmap())
core = characters & (set(range(0x20, 0x7f)) | {0x2010, 0x2013, 0x2014, 0x2018, 0x2019, 0x201c, 0x201d, 0x2026})


def ranges(points):
    runs = []
    for point in sorted(points):
        if runs and point == runs[-1][1] + 1:
            runs[-1][1] = point
        else:
            runs.append([point, point])
    return ', '.join(f'U+{a:04X}' + (f'-{b:04X}' if a != b else '') for a, b in runs)


faces = []
with tempfile.TemporaryDirectory() as tmp:
    original.flavor = None
    ttf = Path(tmp) / 'source.ttf'
    original.save(ttf)
    for name, chars in [('extended', characters - core), ('core', core)]:
        subset_ttf = Path(tmp) / f'{name}.ttf'
        subprocess.run([
            'hb-subset', str(ttf), f'--unicodes={ranges(chars).replace("U+", "").replace(" ", "")}',
            '--layout-features=*', '--no-hinting', f'--output-file={subset_ttf}',
        ], check=True)
        font = TTFont(subset_ttf)
        font.flavor = 'woff2'
        path = out / f'iosevka-{name}.woff2'
        font.save(path)
        actual = set(TTFont(path).getBestCmap())
        assert actual == chars, f'{name}: unexpected character coverage'
        faces.append(f'''@font-face {{
    font-family: "Iosevka";
    font-style: normal;
    font-display: swap;
    font-weight: 400;
    src: url("../assets/fonts/{path.name}") format("woff2");
    unicode-range: {ranges(actual)};
}}''')
        print(f'{path.name}: {path.stat().st_size} bytes, {len(actual)} characters')
css = root / 'src/styles/iosevka.css'
css.write_text('/* Generated by scripts/subset-iosevka.py. */\n' + '\n\n'.join(faces) + '\n')
subprocess.run([str(root / 'node_modules/.bin/biome'), 'format', '--write', str(css)], check=True)
